"""Generate documentary Git timing tables without importing or testing project code.

Run from the repository root with Python 3. Standard library only. The pinned
ranges intentionally remain reproducible when later commits extend the branch.
"""
from collections import defaultdict
from datetime import datetime
from pathlib import Path
import math
import os
import statistics
import subprocess

DIRECTORY = Path(__file__).resolve().parent
HEAD = '2ae737862'
PHASES = [
    ('PR 201 branch', 'ce0101fb^1..ce0101fb^2'),
    ('PR 226 continuation', 'ce0101fb..8f2f6c48'),
    ('Issue 227 continuation', '8f2f6c48..' + HEAD),
]
CATEGORIES = [
    ('DOC', ('checkpoint', 'handoff', 'document', 'record user', 'plan every', 'report delivery', 'case study')),
    ('OPS', ('ci:', 'ci ', 'workflow', 'cache cleanup', 'disk', 'memory', 'resource', 'cancellation')),
    ('MEANING', ('concept', 'ontology', 'taxonomy', 'rdf', 'owl', 'equivalence')),
    ('DISCOVERY', ('grammar inference', 'discovery', 'counterexample refinement', 'held-out')),
    ('GRAMMAR', ('grammar', 'scanner', 'lexer', 'cst', 'lexical source')),
    ('FORMAL', ('lean', 'rocq', 'proof', 'formal datatype')),
    ('RUST', ('rust', 'borrow', 'ownership', 'owned ', 'fnmut', 'box ', 'vec ', 'record field', 'source region', 'source-region', 'source place', 'source patterns')),
    ('JS', ('javascript', 'array', 'object', 'function', 'prototype', 'callback', 'module', 'string', 'utf16', 'bigint', 'reflect', 'property', 'constructor', 'construct ', 'map ', 'set ', 'collection', 'scope', 'loader', 'class ', 'heap', 'callable')),
    ('TRANSPORT', ('links', 'snapshot', 'archive', 'codec', 'binary', 'link identities')),
    ('GENERATION', ('generat', 'publication', 'publish', 'self-translat', 'package', 'consumer', 'native')),
]
DESCRIPTIONS = {
    'DOC': 'Preserving scope, checkpoints or planning; this is not implementation delivery.',
    'OPS': 'Execution, workflow or resource operation; the subject does not measure waiting time.',
    'MEANING': 'Concept identity, formal meaning or ontology/interchange integration.',
    'DISCOVERY': 'Grammar discovery/refinement and its independent controls.',
    'GRAMMAR': 'Grammar/scanner/CST coverage and source-fidelity integration.',
    'FORMAL': 'Formal target representation, dependencies or compiler-facing integration.',
    'RUST': 'Rust source ownership, positions, effects or actual consuming source paths.',
    'JS': 'JavaScript source/runtime semantics, identity, effects or actual consumers.',
    'TRANSPORT': 'Graph/codec/reload identity and actual consumer transport.',
    'GENERATION': 'Generated/native/package integration or publication plumbing.',
    'OTHER': 'Cross-cutting work; inspect the linked subject and diff for the actual scope.',
}
ENVIRONMENT = dict(os.environ, GIT_NO_LAZY_FETCH='1')


def git(*arguments):
    return subprocess.check_output(['git', '-c', 'gc.auto=0', *arguments], text=True, env=ENVIRONMENT)


def category(subject):
    text = subject.lower()
    return next((name for name, words in CATEGORIES if any(word in text for word in words)), 'OTHER')


def read_rows(revision):
    result = []
    for line in git('log', '--first-parent', '--reverse', '--format=%H%x09%aI%x09%cI%x09%s', revision).splitlines():
        sha, author, committer, subject = line.split('\t', 3)
        result.append({'sha': sha, 'author': author, 'committer': committer,
                       'time': datetime.fromisoformat(committer), 'subject': subject,
                       'category': category(subject)})
    return result


def duration(seconds):
    sign = '-' if seconds < 0 else ''
    seconds = abs(round(seconds))
    hours, remainder = divmod(seconds, 3600)
    minutes, seconds = divmod(remainder, 60)
    return f'{sign}{hours:02d}:{minutes:02d}:{seconds:02d}'


def percentile(values, fraction):
    return sorted(values)[math.floor((len(values) - 1) * fraction)]


def escaped(value):
    return value.replace('|', '\\|').replace('\n', ' ')


def link(row):
    return f"[`{row['sha'][:9]}`](https://github.com/link-foundation/meta-language/commit/{row['sha']})"


phases = [(label, revision, read_rows(revision)) for label, revision in PHASES]
lines = [
    '# Complete task commit timing appendix — 2026-11-06', '',
    f'Pinned implementation head: `{git("rev-parse", HEAD).strip()}`.', '',
    'Generated by [build-commit-timing-report.py](build-commit-timing-report.py).',
    'Run `python3 docs/case-studies/issue-227/build-commit-timing-report.py` from the repository root.',
    'This performs read-only Git metadata arithmetic and writes Markdown; it does not import project code, run tests, compile, fetch missing objects or query CI.', '',
    'Each row is one first-parent commit in the stated range. Elapsed is the committer-time gap from the preceding row **in that phase**, not measured active work or feature implementation time.',
    'Both dates are retained because author time and publication/checkpoint time can differ. The first row has no in-phase predecessor. Cross-phase gaps and the merge checkpoint are separate below.',
    'The scope is the three defined task history paths, not every side-branch commit reachable from this repository. No commit is counted twice across the phase ranges.', '',
    'Work labels are deterministic subject-keyword classifications. They describe likely work content, **not an observed cause or allocation of elapsed time**. Mixed commits receive the first matching label.', '',
    '| Work label | Interpretation only |', '| --- | --- |',
]
for name, description in DESCRIPTIONS.items():
    lines.append(f'| {name} | {description} |')
lines += ['', '## Phase measurements', '', '| Phase | Commits | First committed | Last committed | Span | Median gap | Mean gap | P90 gap | P95 gap | Author/committer differ |', '| --- | ---: | --- | --- | --- | --- | --- | --- | --- | ---: |']
for label, revision, rows in phases:
    gaps = [(b['time'] - a['time']).total_seconds() for a, b in zip(rows, rows[1:])]
    lines.append(f"| {label} | {len(rows)} | {rows[0]['committer']} | {rows[-1]['committer']} | {duration(sum(gaps))} | {duration(statistics.median(gaps))} | {duration(statistics.mean(gaps))} | {duration(percentile(gaps, .9))} | {duration(percentile(gaps, .95))} | {sum(row['author'] != row['committer'] for row in rows)} |")
lines += ['', 'Percentiles use the lower empirical order statistic `sorted[floor((n − 1) × p)]`. No negative committer gaps occur in these ranges.', '', '## Cross-phase checkpoints', '']
# Use direct object lookup for the merge itself rather than all first-parent ancestors.
merge_text = git('show', '-s', '--format=%H%x09%aI%x09%cI%x09%s', 'ce0101fb').strip()
sha, author, committer, subject = merge_text.split('\t', 3)
merge = {'sha': sha, 'author': author, 'committer': committer, 'subject': subject, 'time': datetime.fromisoformat(committer)}
lines += [f"PR 201 merge checkpoint: {link(merge)}, {committer}, {escaped(subject)}. This merge is separate from the three phase counts.", '', '| Transition | Elapsed |', '| --- | --- |',
          f"| PR 201 branch head → PR 201 merge | {duration((merge['time'] - phases[0][2][-1]['time']).total_seconds())} |",
          f"| PR 201 merge → first PR 226 commit | {duration((phases[1][2][0]['time'] - merge['time']).total_seconds())} |",
          f"| PR 226 head → first issue 227 continuation commit | {duration((phases[2][2][0]['time'] - phases[1][2][-1]['time']).total_seconds())} |", '']
for label, revision, rows in phases:
    lines += ['## ' + label, '', f'Range: `{revision}`. Command: `git log --first-parent --reverse --format="%H%x09%aI%x09%cI%x09%s" {revision}`.', '', '| Step | Commit | Author date | Committer date | Elapsed since previous | Work label | Exact subject |', '| ---: | --- | --- | --- | --- | --- | --- |']
    for index, row in enumerate(rows):
        gap = '—' if not index else duration((row['time'] - rows[index - 1]['time']).total_seconds())
        lines.append(f"| {index + 1} | {link(row)} | {row['author']} | {row['committer']} | {gap} | {row['category']} | {escaped(row['subject'])} |")
    lines.append('')
(DIRECTORY / 'commit-timing-2026-11-06.md').write_text('\n'.join(lines) + '\n')

current = phases[-1][2]
gaps = [(b['time'] - a['time']).total_seconds() for a, b in zip(current, current[1:])]
summary = ['# Timing calculation notes — 2026-11-06', '', 'Generated documentary arithmetic; see the [main report](delivery-time-analysis-2026-11-06.md).', '', '## Daily continuation commit spans', '', '| Day (+07:00) | Commits | First | Last | First-to-last span | Median same-day gap |', '| --- | ---: | --- | --- | --- | --- |']
days = defaultdict(list)
for row in current:
    days[row['time'].date()].append(row)
for day, rows in sorted(days.items()):
    local_gaps = [(b['time'] - a['time']).total_seconds() for a, b in zip(rows, rows[1:])]
    median = duration(statistics.median(local_gaps)) if local_gaps else '—'
    summary.append(f"| {day} | {len(rows)} | {rows[0]['time'].time()} | {rows[-1]['time'].time()} | {duration((rows[-1]['time'] - rows[0]['time']).total_seconds())} | {median} |")
summary += ['', 'Daily spans are not active work hours. Multiple workers and work crossing midnight can both occur.', '', '## Largest continuation gaps', '', '| Gap | Previous commit | Next commit | Next exact subject |', '| --- | --- | --- | --- |']
for gap, previous, row in sorted(zip(gaps, current, current[1:]), key=lambda item: item[0], reverse=True)[:20]:
    summary.append(f"| {duration(gap)} | {link(previous)} ({previous['committer']}) | {link(row)} ({row['committer']}) | {escaped(row['subject'])} |")
summary += ['', 'These gaps have no measured cause in Git. A report may separately link documentary evidence of a stop; an unexplained gap remains unexplained.', '', '## Short-gap sensitivity', '', '| Maximum included adjacent gap | Included gaps | Sum of included gaps |', '| --- | ---: | --- |']
for threshold in [30, 60, 120, 240]:
    selected = [gap for gap in gaps if 0 <= gap <= threshold * 60]
    summary.append(f'| {threshold} minutes | {len(selected)} | {duration(sum(selected))} |')
summary += ['', 'This is a sensitivity calculation, **not session detection or active work accounting**. Threshold selection changes the answer and cannot recover unrecorded labor.', '', '## Recent intervals', '', '| Commit | Gap from predecessor | Exact subject |', '| --- | --- | --- |']
for index in range(max(1, len(current) - 32), len(current)):
    row = current[index]
    summary.append(f"| {link(row)} | {duration((row['time'] - current[index - 1]['time']).total_seconds())} | {escaped(row['subject'])} |")
summary += ['', '## Checkpoint counts', '', f'Three phase ranges: {sum(len(rows) for _, _, rows in phases):,} distinct commits. With the separate PR 201 merge: {sum(len(rows) for _, _, rows in phases) + 1:,} task checkpoints.', '']
(DIRECTORY / 'commit-timing-calculations-2026-11-06.md').write_text('\n'.join(summary) + '\n')
print('Wrote two Markdown timing appendices for', sum(len(rows) for _, _, rows in phases), 'phase commits; no project execution.')
