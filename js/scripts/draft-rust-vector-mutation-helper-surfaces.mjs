// Publish the actual shared compiler surfaces without running any lowered helper.
import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';
import {buildRustExclusiveSourceVectorHelperBody} from '../src/translation/rust-vector-mutation-helper-surface.js';
import {writeProjectData} from './project-data.mjs';

if(process.argv.slice(2).join(' ')!=='--draft')throw new TypeError('use --draft');
const root=new URL('../../',import.meta.url);
const source='js/src/translation/rust-vector-mutation-helper-surface.js';
const digest=value=>createHash('sha256').update(value).digest('hex');
const placeholder=name=>({sourceVectorMutationTemplateParameter:name});
const bindings={
 parameters:[placeholder('vectorParameter'),placeholder('boundParameter')],
 accumulator:placeholder('accumulator'),
 item:placeholder('item'),
 prior:placeholder('prior'),
 held:placeholder('held'),
 constructors:{None:placeholder('nonePath'),Some:placeholder('somePath')},
};
const layout={element:placeholder('element'),packet:{...placeholder('packet'),elements:[null,placeholder('vector')]},span:placeholder('span')};
const templates=Object.fromEntries(['clear','pop','truncate'].map(operation=>[
 operation,buildRustExclusiveSourceVectorHelperBody(operation,bindings,layout.element,layout.packet,layout.span),
]));
function retainPlaceholders(value) {
 if(value===null||typeof value!=='object')return value;
 if(Object.hasOwn(value,'sourceVectorMutationTemplateParameter'))return placeholder(value.sourceVectorMutationTemplateParameter);
 if(Array.isArray(value))return value.map(retainPlaceholders);
 return Object.fromEntries(Object.entries(value).map(([key,child])=>[key,retainPlaceholders(child)]));
}
const transport=retainPlaceholders(templates);
const output='rust/src/translation/rust_vector_mutation_helper_surfaces.rs';
const rust='// Generated by draft-rust-vector-mutation-helper-surfaces.mjs.\n'+Object.entries(transport)
 .map(([operation,template])=>'pub(crate) const '+operation.toUpperCase()+': &str = r#"'+JSON.stringify(template,null,2)+'"#;\n')
 .join('');
writeFileSync(new URL(output,root),rust);
writeProjectData(new URL('parity/self-translation/rust-vector-mutation-helper-surfaces.lino',root),{
 schemaVersion:1,model:'Complete Rust Vec helper source surfaces 1',source,sourceSha256:digest(readFileSync(new URL(source,root))),
 output,outputSha256:digest(rust),templates:transport,
});
