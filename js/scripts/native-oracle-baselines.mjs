import { readProjectData } from './project-data.mjs';

const { baselines, profileBaselines, fixtureOracle } = readProjectData(new URL('../../parity/grammars/native-oracle-baselines.lino', import.meta.url));

/** The oracle for a candidate grammar exercised by a native scanner profile. */
export function nativeProfileOracleBaseline(language) {
  return profileBaselines[language];
}

/** Historical fixture trees keep their recorded CLI and unchanged grammar parsers. */
export function fixtureOracleToolMatches(recorded, lock) {
  return recorded === lock.treeSitterCli
    || (recorded === fixtureOracle.recorded && lock.treeSitterCli === fixtureOracle.active
      && Object.entries(fixtureOracle.parsers).every(([id, digest]) => lock.grammars[id]?.parserSha256 === digest));
}

/** The independent grammar used to derive this exact native grammar version. */
export function nativeOracleBaseline(native) {
  const baseline = baselines[native.id];
  if (baseline && baseline.nativeVersion !== native.version) {
    throw new Error(`native grammar ${native.id} ${native.version} has no registered baseline (expected ${baseline.nativeVersion})`);
  }
  return baseline;
}

export function nativeOracleBaselineRustSource() {
  return '// Generated by js/scripts/build-language-catalog.mjs. Do not edit.\n'
    + 'native_oracle_baselines! {\n'
    + Object.values({ ...baselines, ...profileBaselines }).map(({ grammar, archiveName, archivePath, symbol }) =>
      `    (\n        ${JSON.stringify(grammar.id)},\n        ${JSON.stringify(grammar.version)},\n`
      + `        ${JSON.stringify(archiveName)},\n        ${JSON.stringify(archivePath)},\n`
      + `        ${JSON.stringify(symbol)},\n        ${symbol}_baseline,\n    ),\n`).join('')
    + '}\n';
}
