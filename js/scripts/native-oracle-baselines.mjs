import { readProjectData } from './project-data.mjs';

const { baselines } = readProjectData(new URL('../../parity/grammars/native-oracle-baselines.lino', import.meta.url));

/** The independent grammar used to derive this exact native grammar version. */
export function nativeOracleBaseline(native) {
  const baseline = baselines[native.id];
  if (baseline && baseline.nativeVersion !== native.version) {
    throw new Error(`native grammar ${native.id} ${native.version} has no registered baseline (expected ${baseline.nativeVersion})`);
  }
  return baseline;
}

export function nativeOracleBaselineRustSource() {
  return '// Generated by js/scripts/build-language-catalog.mjs. Do not edit.\n'
    + 'native_oracle_baselines! {\n'
    + Object.values(baselines).map(({ grammar, archiveName, archivePath, symbol }) =>
      `    (\n        ${JSON.stringify(grammar.id)},\n        ${JSON.stringify(grammar.version)},\n`
      + `        ${JSON.stringify(archiveName)},\n        ${JSON.stringify(archivePath)},\n`
      + `        ${JSON.stringify(symbol)},\n        ${symbol}_baseline,\n    ),\n`).join('')
    + '}\n';
}
