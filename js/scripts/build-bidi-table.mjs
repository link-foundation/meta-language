#!/usr/bin/env node
// Generates src/unicode-bidi-classes.js from the bidi_class_table of the
// unicode-bidi crate used by the Rust runtime, so both runtimes resolve the
// paragraph direction (UAX #9 rules P2/P3) from identical Unicode data.
//
// Usage: node scripts/build-bidi-table.mjs <path to unicode-bidi/src/char_data/tables.rs> [--check]
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const [tablesPath] = process.argv.slice(2).filter((argument) => !argument.startsWith('--'));
if (!tablesPath) throw new Error('pass the path to unicode-bidi src/char_data/tables.rs');
const output = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'unicode-bidi-classes.js');
const tables = await readFile(tablesPath, 'utf8');
const version = tables.match(/UNICODE_VERSION: \(u64, u64, u64\) = \((\d+), (\d+), (\d+)\)/).slice(1).join('.');
const body = tables.slice(tables.indexOf('bidi_class_table'));
const table = body.slice(0, body.indexOf('];'));

// Only the classes rules P2/P3 inspect are kept; code points outside every
// range default to L, as in the crate.
const category = { L: 'L', R: 'R', AL: 'R', B: 'B', LRI: 'I', RLI: 'I', FSI: 'I', PDI: 'P' };
const ranges = [];
for (const [, start, end, bidiClass] of table.matchAll(/\('\\u\{([0-9a-f]+)\}', '\\u\{([0-9a-f]+)\}', (\w+)\)/g)) {
  const kind = category[bidiClass] ?? 'N';
  const range = [Number.parseInt(start, 16), Number.parseInt(end, 16), kind];
  const previous = ranges.at(-1);
  if (previous && previous[2] === kind && previous[1] + 1 === range[0]) previous[1] = range[1];
  else ranges.push(range);
}
const nonDefault = ranges.filter(([, , kind]) => kind !== 'L');
const source = `// Generated by scripts/build-bidi-table.mjs from the unicode-bidi crate's
// bidi_class_table (Unicode ${version}). Do not edit by hand.
// Kinds: R = R/AL, B = paragraph separator, I = isolate initiator,
// P = PDI, N = any other non-L class. Unlisted code points are L.
export const UNICODE_BIDI_VERSION = '${version}';
export const BIDI_RANGES = ${JSON.stringify(nonDefault.map(([start, end, kind]) => `${start.toString(36)}.${end.toString(36)}.${kind}`).join(' '))};
`;
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== source) throw new Error(`${output} is stale`);
  console.log('unicode bidi table is current');
} else {
  await writeFile(output, source);
  console.log(`wrote ${nonDefault.length} ranges to ${output}`);
}
