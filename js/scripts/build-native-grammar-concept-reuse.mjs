#!/usr/bin/env node
// Generates the per-language concept reuse report of the native grammars
// (requirement I195-GRAMMAR-SHARED-CONCEPTS, published with the merge quality
// evidence of I195-MERGE-QUALITY-EVIDENCE): for every native grammar, the
// rules that name a concept two or more native grammars share and the rules
// that name a concept specific to that language, and every concept with the
// languages that name it. Both runtimes compute the same report; the JSON
// file is the fixture their tests compare against.
//
//   node js/scripts/build-native-grammar-concept-reuse.mjs          # write the report
//   node js/scripts/build-native-grammar-concept-reuse.mjs --check  # fail on drift
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { checkNativeGrammarConcepts, nativeGrammarConceptReuse } from '../src/grammar-concepts.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const CONCEPT_REUSE_FIXTURE = 'parity/fixtures/native-grammar-concept-reuse.json';
export const CONCEPT_REUSE_DOCUMENT = 'docs/grammar/native-grammar-concept-reuse.md';

export function formatConceptReuse(report) {
  const grammars = report.grammars.map(({ grammar, language, rules, shared, specific }) => [
    '    {',
    `      "grammar": ${JSON.stringify(grammar)},`,
    `      "language": ${JSON.stringify(language)},`,
    `      "rules": ${rules},`,
    `      "shared": [${shared.map((entry) => `\n        ${JSON.stringify(entry)}`).join(',')}${shared.length > 0 ? '\n      ' : ''}],`,
    `      "specific": [${specific.map((entry) => `\n        ${JSON.stringify(entry)}`).join(',')}${specific.length > 0 ? '\n      ' : ''}]`,
    '    }',
  ].join('\n'));
  const concepts = report.concepts.map((entry) => `    ${JSON.stringify(entry)}`);
  return [
    '{',
    '  "generatedBy": "js/scripts/build-native-grammar-concept-reuse.mjs",',
    '  "grammars": [',
    grammars.join(',\n'),
    '  ],',
    '  "concepts": [',
    concepts.join(',\n'),
    '  ]',
    '}',
    '',
  ].join('\n');
}

const percent = (part, whole) => `${whole === 0 ? 0 : Math.round((100 * part) / whole)}%`;
const code = (text) => `\`${text}\``;

export function renderConceptReuseDocument(report) {
  const lines = [
    '# Concept reuse of the native grammars',
    '',
    'Generated by `node js/scripts/build-native-grammar-concept-reuse.mjs` from the',
    'native grammars in `parity/grammars/native/` and the concept records in',
    '`parity/naming/canonical-concepts.json`; do not edit it by hand. The same',
    `report is ${code(CONCEPT_REUSE_FIXTURE)}, which both runtimes' tests compare`,
    'against. It is part of the merge quality evidence (`I195-MERGE-QUALITY-EVIDENCE`).',
    '',
    'Every rule of every native grammar names a canonical concept record with',
    '`(concept ID)`. A rule is **shared** when two or more native grammars name its',
    'concept, so the construct translates between those languages through the',
    'concept with no rule for the pair of languages; it is **language-specific**',
    'when only its own grammar names the concept.',
    '',
    '## Per language',
    '',
    '| Grammar | Rules | Shared | Language-specific | Shared share |',
    '| --- | ---: | ---: | ---: | ---: |',
  ];
  for (const { grammar, rules, shared, specific } of report.grammars) {
    lines.push(`| ${code(grammar)} | ${rules} | ${shared.length} | ${specific.length} | ${percent(shared.length, rules)} |`);
  }
  const total = report.grammars.reduce((sum, { rules }) => sum + rules, 0);
  const shared = report.grammars.reduce((sum, entry) => sum + entry.shared.length, 0);
  lines.push(`| all | ${total} | ${shared} | ${total - shared} | ${percent(shared, total)} |`, '');
  for (const { grammar, shared: sharedRules, specific } of report.grammars) {
    lines.push(`### ${code(grammar)}`, '');
    lines.push(`- Shared: ${sharedRules.map(({ rule, concept }) => `${code(rule)} → ${code(concept)}`).join(', ') || 'none'}.`);
    lines.push(`- Language-specific: ${specific.map(({ rule, concept }) => `${code(rule)} → ${code(concept)}`).join(', ') || 'none'}.`, '');
  }
  lines.push('## Shared concepts', '', '| Concept | Languages |', '| --- | --- |');
  for (const { concept, languages } of report.concepts.filter((entry) => entry.shared)) {
    lines.push(`| ${code(concept)} | ${languages.join(', ')} |`);
  }
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const problems = checkNativeGrammarConcepts();
  if (problems.length > 0) {
    for (const { kind, grammar, rule, concept } of problems) console.error(`${grammar} ${rule}: ${kind}${concept ? ` (${concept})` : ''}`);
    process.exit(1);
  }
  const report = nativeGrammarConceptReuse();
  const outputs = [
    [CONCEPT_REUSE_FIXTURE, formatConceptReuse(report)],
    [CONCEPT_REUSE_DOCUMENT, renderConceptReuseDocument(report)],
  ];
  if (process.argv.includes('--check')) {
    const stale = [];
    for (const [path, text] of outputs) {
      if ((await readFile(join(root, path), 'utf8').catch(() => '')) !== text) stale.push(path);
    }
    if (stale.length > 0) {
      console.error(`the native grammar concept reuse report is stale: ${stale.join(', ')}`);
      console.error('run: node js/scripts/build-native-grammar-concept-reuse.mjs');
      process.exit(1);
    }
    console.log(`the concept reuse report matches ${report.grammars.length} native grammars and ${report.concepts.length} concepts`);
    return;
  }
  await Promise.all(outputs.map(([path, text]) => writeFile(join(root, path), text)));
  console.log(`wrote the concept reuse report of ${report.grammars.length} native grammars`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
