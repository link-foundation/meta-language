// Lists the root-level constants of Lean's prelude (`Init`), which a root
// declaration of an emitted Lean program may not redeclare, and writes them
// to src/translation/lean-root-names.js and rust/src/translation/lean_root_names.rs.
// Requires `lean` on PATH.
// Usage: node scripts/build-lean-root-names.mjs [--check]
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROGRAM = `import Lean
open Lean in
def main : IO Unit := do
  initSearchPath (← findSysroot)
  let env ← importModules #[{ module := \`Init }] {}
  let mut names : Array String := #[]
  for (name, _) in env.constants.toList do
    match name with
    | .str .anonymous s => if !name.isInternal then names := names.push s
    | _ => pure ()
  for n in names.qsort (· < ·) do IO.println n
`;

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const targets = {
  js: join(root, 'js', 'src', 'translation', 'lean-root-names.js'),
  rust: join(root, 'rust', 'src', 'translation', 'lean_root_names.rs'),
};
const work = mkdtempSync(join(tmpdir(), 'lean-roots-'));
writeFileSync(join(work, 'Roots.lean'), PROGRAM);
const version = execFileSync('lean', ['--version'], { encoding: 'utf8' }).trim();
const names = execFileSync('lean', ['--run', 'Roots.lean'], { cwd: work, encoding: 'utf8', maxBuffer: 1 << 26 })
  .split('\n')
  .filter((name) => /^[A-Za-z_][A-Za-z0-9_']*$/u.test(name));
const leanVersion = version.match(/\d+\.\d+\.\d+/u)[0];
const lines = (indent) => {
  const out = [];
  for (let index = 0; index < names.length; index += 8) out.push(`${indent}${names.slice(index, index + 8).map((name) => JSON.stringify(name)).join(', ')},`);
  return out.join('\n');
};
const texts = {
  js: `// Generated by scripts/build-lean-root-names.mjs from Lean ${leanVersion}; do not edit.
// Root-level constants of Lean's prelude, which a root declaration may not redeclare.
export const LEAN_ROOT_NAMES = Object.freeze([
${lines('  ')}
]);
`,
  rust: `//! Generated by js/scripts/build-lean-root-names.mjs from Lean ${leanVersion}; do not edit.
//!
//! Root-level constants of Lean's prelude, which a root declaration may not redeclare.

#[rustfmt::skip]
pub const LEAN_ROOT_NAMES: &[&str] = &[
${lines('    ')}
];
`,
};
for (const [runtime, target] of Object.entries(targets)) {
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== texts[runtime]) {
      console.error(`${target} is stale; run node scripts/build-lean-root-names.mjs`);
      process.exitCode = 1;
    }
  } else {
    writeFileSync(target, texts[runtime]);
    console.log(`${names.length} names written to ${target}`);
  }
}
