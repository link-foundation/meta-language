#!/usr/bin/env node
// Generates the shared trigram language-identification data used by both
// runtimes from franc-min (MIT, Titus Wormer): the script detection ranges of
// every franc script, the trigram models of the ten supported natural
// languages, and competing Cyrillic models from franc. Both runtimes read the
// same Links Notation data and implement the same algorithm over it.
//
// Usage: node scripts/build-language-identification.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkProjectData, writeProjectData } from './project-data.mjs';

import { data } from 'franc-min/data.js';
import { expressions } from 'franc-min/expressions.js';
import { data as extendedData } from 'franc/data.js';
import { buildLanguageIdentificationConfidence } from './build-language-identification-confidence.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const dataOutputs = ['js', 'rust'].map(runtime => path.join(root, runtime, 'src', 'data', 'language-trigrams.lino'));
const moduleOutput = path.join(root, 'js', 'src', 'language-trigrams.js');
const francVersion = JSON.parse(
  await readFile(path.join(root, 'js', 'node_modules', 'franc-min', 'package.json'), 'utf8'),
).version;
const extendedVersion = JSON.parse(
  await readFile(path.join(root, 'js', 'node_modules', 'franc', 'package.json'), 'utf8'),
).version;

// ISO 639-3 codes of the supported natural languages, in the order the
// runtimes report them.
const LANGUAGES = {
  eng: 'English',
  cmn: 'Mandarin Chinese',
  hin: 'Hindi',
  spa: 'Spanish',
  arb: 'Modern Standard Arabic',
  fra: 'French',
  ben: 'Bengali',
  por: 'Portuguese',
  rus: 'Russian',
  urd: 'Urdu',
};

const CYRILLIC_LANGUAGES = {
  ukr: 'Ukrainian',
  srp: 'Serbian',
  bel: 'Belarusian',
  bul: 'Bulgarian',
  kaz: 'Kazakh',
  kir: 'Kyrgyz',
  tgk: 'Tajik',
  khk: 'Mongolian',
};

// Main Cyrillic exemplar characters from Unicode CLDR 48, with digraphs
// split into letters and the Ukrainian modifier apostrophe omitted.
const CYRILLIC_ALPHABETS = {
  rus: 'абвгдеёжзийклмнопрстуфхцчшщъыьэюя',
  ukr: 'абвгґдеєжзиіїйклмнопрстуфхцчшщьюя',
  srp: 'абвгдђежзијклљмнњопрстћуфхцчџш',
  bel: 'абвгдеёжзійклмнопрстуўфхцчшыьэюя',
  bul: 'абвгдежзийклмнопрстуфхцчшщъьюя',
  kaz: 'аәбвгғдеёжзийкқлмнңоөпрстуұүфхһцчшщъыіьэюя',
  kir: 'абгдеёжзийклмнңоөпрстуүхчшъыэюя',
  tgk: 'абвгғдеёжзиӣйкқлмнопрстуӯфхҳчҷшъэюя',
  khk: 'абвгдеёжзийклмноөпрстуүфхцчшщъыьэюя',
};

const scripts = Object.entries(expressions).map(([name, expression]) => {
  const single = new RegExp(`^(?:${expression.source})$`, 'u');
  const ranges = [];
  for (let codePoint = 0; codePoint <= 0x10ffff; codePoint += 1) {
    if (codePoint >= 0xd800 && codePoint <= 0xdfff) continue;
    if (!single.test(String.fromCodePoint(codePoint))) continue;
    const previous = ranges.at(-1);
    if (previous && previous[1] + 1 === codePoint) previous[1] = codePoint;
    else ranges.push([codePoint, codePoint]);
  }
  return { name, ranges };
});

const models = Object.entries(data).map(([script, languages]) => ({
  script,
  languages: Object.entries(languages)
    .filter(([code]) => code in LANGUAGES)
    .map(([code, trigrams]) => ({ code, trigrams })),
}));
models.find(({ script }) => script === 'Cyrillic').languages.push(
  ...Object.keys(CYRILLIC_LANGUAGES).map((code) => {
    const trigrams = extendedData.Cyrillic[code];
    if (trigrams === undefined) throw new Error(`Missing franc Cyrillic model ${code}`);
    return { code, trigrams };
  }),
);

const shared = {
  source: `franc-min ${francVersion} (MIT, Titus Wormer)`,
  cyrillicSource: `franc ${extendedVersion} (MIT, Titus Wormer)`,
  cyrillicAlphabetSource: 'https://github.com/unicode-org/cldr/tree/acd6d88ae493633240e19a87a721076a8a75c310/common/main',
  languages: LANGUAGES,
  cyrillicLanguages: CYRILLIC_LANGUAGES,
  cyrillicAlphabets: CYRILLIC_ALPHABETS,
  scripts,
  models,
};
const module = `// Generated by scripts/build-language-identification.mjs from franc-min
// ${francVersion} and franc ${extendedVersion} (MIT, Titus Wormer). Both runtimes
// read identical packaged data/language-trigrams.lino.
import { readRuntimeProjectData } from './project-data-loader.js';
export const LANGUAGE_TRIGRAMS = readRuntimeProjectData(new URL('./data/language-trigrams.lino', import.meta.url));
`;

if (process.argv.includes('--check')) {
  for (const file of dataOutputs) checkProjectData(file, shared);
  if ((await readFile(moduleOutput, 'utf8')) !== module) throw new Error(`${moduleOutput} is stale`);
  console.log('language identification data is current');
} else {
  for (const file of dataOutputs) writeProjectData(file, shared);
  await writeFile(moduleOutput, module);
  console.log(`wrote ${scripts.length} scripts and ${models.length} models`);
}
buildLanguageIdentificationConfidence(process.argv.includes('--check'));
