#!/usr/bin/env node
// Generates the shared trigram language-identification data used by both
// runtimes from franc-min (MIT, Titus Wormer): the script detection ranges of
// every franc script, and the trigram models of the ten supported natural
// languages. The Rust runtime embeds the JSON file; the JavaScript runtime
// imports the generated module. Both implement the same algorithm over it.
//
// Usage: node scripts/build-language-identification.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { data } from 'franc-min/data.js';
import { expressions } from 'franc-min/expressions.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const jsonOutput = path.join(root, 'rust', 'src', 'data', 'language-trigrams.json');
const moduleOutput = path.join(root, 'js', 'src', 'language-trigrams.js');
const francVersion = JSON.parse(
  await readFile(path.join(root, 'js', 'node_modules', 'franc-min', 'package.json'), 'utf8'),
).version;

// ISO 639-3 codes of the supported natural languages, in the order the
// runtimes report them.
const LANGUAGES = {
  eng: 'English',
  cmn: 'Mandarin Chinese',
  hin: 'Hindi',
  spa: 'Spanish',
  arb: 'Modern Standard Arabic',
  fra: 'French',
  ben: 'Bengali',
  por: 'Portuguese',
  rus: 'Russian',
  urd: 'Urdu',
};

const scripts = Object.entries(expressions).map(([name, expression]) => {
  const single = new RegExp(`^(?:${expression.source})$`, 'u');
  const ranges = [];
  for (let codePoint = 0; codePoint <= 0x10ffff; codePoint += 1) {
    if (codePoint >= 0xd800 && codePoint <= 0xdfff) continue;
    if (!single.test(String.fromCodePoint(codePoint))) continue;
    const previous = ranges.at(-1);
    if (previous && previous[1] + 1 === codePoint) previous[1] = codePoint;
    else ranges.push([codePoint, codePoint]);
  }
  return { name, ranges };
});

const models = Object.entries(data).map(([script, languages]) => ({
  script,
  languages: Object.entries(languages)
    .filter(([code]) => code in LANGUAGES)
    .map(([code, trigrams]) => ({ code, trigrams })),
}));

const shared = {
  source: `franc-min ${francVersion} (MIT, Titus Wormer)`,
  languages: LANGUAGES,
  scripts,
  models,
};
const json = `${JSON.stringify(shared, null, 1)}\n`;
const module = `// Generated by scripts/build-language-identification.mjs from franc-min
// ${francVersion} (MIT, Titus Wormer). Do not edit by hand; the Rust runtime
// embeds the identical rust/src/data/language-trigrams.json.
export const LANGUAGE_TRIGRAMS = ${JSON.stringify(shared)};
`;

if (process.argv.includes('--check')) {
  for (const [file, expected] of [[jsonOutput, json], [moduleOutput, module]]) {
    if ((await readFile(file, 'utf8')) !== expected) throw new Error(`${file} is stale`);
  }
  console.log('language identification data is current');
} else {
  await writeFile(jsonOutput, json);
  await writeFile(moduleOutput, module);
  console.log(`wrote ${scripts.length} scripts and ${models.length} models`);
}
