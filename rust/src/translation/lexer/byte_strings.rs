//! Byte/source and token transport around the automatically translated decoder.
use super::{
    Language, Result, Source, Token, TokenKind, TranslationError, identifiers,
    is_identifier_part_at, is_identifier_start_at, span,
};
use crate::translation::rust_byte_string_rules as rules;

#[allow(clippy::float_cmp)] // The shared packet has exact discrete numeric tags.
pub(super) fn read(
    source: &Source,
    index: usize,
    units: &mut Option<Vec<f64>>,
) -> Result<Option<Token>> {
    let encoded =
        units.get_or_insert_with(|| source.units().iter().map(|unit| f64::from(*unit)).collect());
    let start = serde_json::Number::from(index)
        .as_f64()
        .expect("UTF-16 source offset");
    let literal = rules::decode_rust_byte_string_literal(encoded, start);
    let code = literal[0];
    if code == 0.0 {
        return Ok(None);
    }
    let position = |value| {
        crate::translation::frontend_rules::ml_array::number_index(value)
            .expect("generated byte string source offset")
    };
    if code < 0.0 {
        return Err(TranslationError::syntax(
            rules::read_rust_byte_string_literal_error(code).to_string(),
            Some(span(position(literal[1]), position(literal[2]))),
        ));
    }
    let literal_end = position(literal[1]);
    let mut end = literal_end;
    if is_identifier_start_at(source, end, Language::Rust)
        && !(source.is_char(end, '_') && !is_identifier_part_at(source, end + 1, Language::Rust))
    {
        end += identifiers::width(source, end);
        while end < source.len() && is_identifier_part_at(source, end, Language::Rust) {
            end += identifiers::width(source, end);
        }
    }
    let value = rules::render_rust_byte_string_value(&literal[2..]).to_string();
    let mut token = Token::new(
        TokenKind::ByteString,
        value,
        source.slice(index, end),
        index,
        end,
    );
    token.suffix = source.slice(literal_end, end);
    Ok(Some(token))
}
